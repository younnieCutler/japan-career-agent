def error_message(language: Any, code: str | None, fallback: str | None = None) -> str:
    key = {
        "INVALID_INPUT": "error.guided_choice",
        "SETUP_REQUIRED": "reason.setup_required",
        "PROPOSAL_NOT_FOUND": "reason.operation_blocked",
        "PROPOSAL_NOT_PENDING": "reason.operation_blocked",
        "EVIDENCE_REQUIRED": "action.provide_evidence",
        "EVIDENCE_MISMATCH": "action.provide_matching_evidence",
    }.get(str(code or ""), "reason.operation_blocked")
    return text(language, key) if key.startswith("reason.") or key.startswith("action.") else (fallback or text(language, "error.generic"))


