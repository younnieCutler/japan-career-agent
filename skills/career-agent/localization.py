DOMAIN_ROWS = {
    namespace: {_domain_token(value): labels for value, labels in values.items()}
    for namespace, values in _DOMAIN_ROWS.items()
}
_DOMAIN_LANGUAGE_INDEX = {"ko": 0, "ja": 1, "en": 2}


def normalize_language(value: Any) -> str:
    raw = str(value or "").casefold().replace("_", "-")
    base = raw.split("-", 1)[0]
    return base if base in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def gui_catalog(language: Any) -> dict[str, str]:
    """The presentation-only GUI catalog; canonical stored values never pass through it."""
    locale = normalize_language(language)
    catalog = dict(GUI_TEXT[locale])
    index = _DOMAIN_LANGUAGE_INDEX[locale]
    for group, namespace in {
        "track": "track",
        "external_use": "external_use",
        "context_kind": "context_kind",
        "confidence": "confidence",
        "document": "document_type",
        "project_status": "project_status",
        "self_analysis_state": "self_analysis_state",
        "case_status": "case_status",
        # Readiness reports one state per dimension and never a total. Both the dimension names
        # and the states they take are already translated for the CLI, so the GUI projects the
        # same rows rather than keeping a second copy that could drift from it.
        "readiness": "fact_state",
        "readiness_dimension": "readiness_dimension",
    }.items():
        for value, labels in DOMAIN_ROWS[namespace].items():
            catalog[f"enum.{group}.{value}"] = labels[index]
    return catalog


def validate_gui_catalog() -> list[str]:
    expected = set(gui_catalog(DEFAULT_LANGUAGE))
    return [locale for locale in SUPPORTED_LANGUAGES if set(gui_catalog(locale)) != expected]


def text(language: Any, translation_key: str, **values: Any) -> str:
    """Resolve a catalog key; missing keys fail loudly instead of leaking identifiers."""
    locale = normalize_language(language)
    template = UX_TEXT.get(locale, {}).get(translation_key) or UX_TEXT["en"].get(translation_key) or UX_TEXT[DEFAULT_LANGUAGE].get(translation_key)
    if template is None:
        raise KeyError(f"missing UX translation: {translation_key}")
    return template.format(**values)


def domain_label(language: Any, namespace: str, value: Any) -> str:
    """Translate one canonical value at a human boundary; unknown values never leak raw."""
    locale = normalize_language(language)
    try:
        labels = DOMAIN_ROWS[str(namespace)][_domain_token(value)]
    except KeyError as exc:
        raise KeyError(f"missing domain translation: {namespace}.{_domain_token(value)}") from exc
    return labels[_DOMAIN_LANGUAGE_INDEX[locale]]


def artifact_kind_label(language: Any, value: Any) -> str:
    """Free-form artifact kinds use a safe user concept instead of exposing a token."""
    try:
        return domain_label(language, "artifact_kind", value)
    except KeyError:
        return domain_label(language, "artifact_kind", "other")


def validate_domain_catalog() -> list[str]:
    errors: list[str] = []
    for namespace, values in DOMAIN_ROWS.items():
        if not values:
            errors.append(f"empty namespace: {namespace}")
        for value, labels in values.items():
            if len(labels) != len(SUPPORTED_LANGUAGES) or not all(
                isinstance(label, str) and label for label in labels
            ):
                errors.append(f"invalid labels: {namespace}.{value}")
    return errors


def catalog_keys() -> set[str]:
    return set(UX_TEXT[DEFAULT_LANGUAGE])


